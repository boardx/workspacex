import { it, expect, afterEach } from 'vitest';
import { mkdtempSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { manifestDigest } from './lib/batch-integration';
const dirs: string[] = [];
afterEach(() => dirs.splice(0).forEach(dir => rmSync(dir, { recursive: true, force: true })));
it('rejects tampered receipt before invoking any GitHub mutation', () => {
    const dir = mkdtempSync(join(tmpdir(), 'batch-cli-'));
    dirs.push(dir);
    const receipt = join(dir, 'receipt.json');
    const core = { version: 1, repository: 'org/repo', base: 'a'.repeat(40), members: [], candidate: { commit: 'b'.repeat(40), tree: 'c'.repeat(40) } };
    const digest = manifestDigest(core);
    writeFileSync(receipt, JSON.stringify({ ...core, digest, branch: `codex/batch-${digest.slice(0, 20)}`, base: 'd'.repeat(40) }));
    const result = spawnSync(process.execPath, ['--import', 'tsx', resolve('.harness/scripts/batch-integration.ts'), 'open', receipt], { encoding: 'utf8', timeout: 15000, env: { ...process.env, GH_TOKEN: '', GITHUB_TOKEN: '' } });
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('Invalid receipt digest');
});
it('rejects unknown command without invoking GitHub', () => {
    const dir = mkdtempSync(join(tmpdir(), 'batch-cli-'));
    dirs.push(dir);
    const receipt = join(dir, 'receipt.json');
    const core = { version: 1, repository: 'org/repo', base: 'a'.repeat(40), members: [], candidate: { commit: 'b'.repeat(40), tree: 'c'.repeat(40) } };
    const digest = manifestDigest(core);
    writeFileSync(receipt, JSON.stringify({ ...core, digest, branch: `codex/batch-${digest.slice(0, 20)}` }));
    const result = spawnSync(process.execPath, ['--import', 'tsx', resolve('.harness/scripts/batch-integration.ts'), 'merge', receipt], { encoding: 'utf8', timeout: 15000 });
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('Unknown action');
});
import { mkdirSync, chmodSync } from 'node:fs';
