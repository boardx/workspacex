    writeFileSync(state, JSON.stringify(merged));
    result = run('reconcile', singletonPath);
    expect(result.status, result.stderr).toBe(0);
    expect(JSON.parse(result.stdout).source).toBe(source);
    merged.jobs[0].run_attempt = 1;
    writeFileSync(state, JSON.stringify(merged));
    result = run('reconcile', singletonPath);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('current-attempt');
    merged.jobs[0].run_attempt = 2;
    const historicalRun = { ...merged.runs[0] };
    merged.attempts = { '200:2': historicalRun };
    merged.runs[0] = { ...historicalRun, run_attempt: 3, run_started_at: '2026-01-02T00:00:00Z', updated_at: '2026-01-02T00:30:00Z' };
    writeFileSync(state, JSON.stringify(merged));
    result = run('reconcile', singletonPath);
    expect(result.status, result.stderr).toBe(0);
    merged.attempts['200:2'] = { ...historicalRun, conclusion: 'failure' };
