"""Derive the complete execution view; never modify the frozen inventory."""
import collections
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read(name):
    with (ROOT / name).open() as handle:
        return list(csv.DictReader(handle))


inventory = read("inventory.csv")
assert len(inventory) == 558
ids = {row["id"] for row in inventory}
assert len(ids) == 558
overlays = {}
for name in ("template-ui-results.csv", "parent-ui-results.csv"):
    for row in read(name):
        assert row["id"] in ids and row["id"] not in overlays
        overlays[row["id"]] = (name, row)
results = []
for item in inventory:
    overlay_file, actual = overlays.get(item["id"], ("", {}))
    excluded = item["boundary"] == "EXCLUDED_QR"
    assert not excluded or item["id"] == "SV26-0516"
    results.append({
        "id": item["id"], "batch": item["batch"], "route": item["route"],
        "control": item["control"], "expected": item["expected"],
        "status": "EXCLUDED" if excluded else actual.get("status", "NOT_STARTED"),
        "actual_source_sha": actual.get("source_sha", ""),
        "result": actual.get("result", "No accepted execution result recorded"),
        "evidence": actual.get("evidence", ""), "overlay_file": overlay_file,
        "boundary": item["boundary"],
    })
counts = collections.Counter(row["status"] for row in results)
assert counts["EXCLUDED"] == 1 and sum(counts.values()) == 558
for name, rows in (("execution-results.csv", results),
                   ("remaining-results.csv", [row for row in results if row["status"] != "PASS"])):
    with (ROOT / name).open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(results[0]))
        writer.writeheader()
        writer.writerows(rows)
summary = ["# Complete inventory execution view", "",
           "Generated by `python3 reconcile-results.py` from the frozen 558-case inventory and the two execution overlays. These are derived views, not a new source of verdicts.", "",
           "| Status | Cases |", "| --- | ---: |"]
summary += [f"| {status} | {counts[status]} |" for status in
            ("PASS", "BLOCKED", "NOT_AVAILABLE", "NOT_STARTED", "EXCLUDED")]
summary += ["", f"Total: 558; only SV26-0516 (QR) is excluded. NOT_AVAILABLE remains in the denominator. PASS is limited to each row's actual source and recorded sample; {counts['PASS']} PASS does not mean the 558-case task is complete.", "",
            "`execution-results.csv` preserves every case. `remaining-results.csv` lists every non-PASS case, including the single exclusion, with its exact control, expected behavior and boundary. Unexecuted baseline rows remain NOT_STARTED; no historical PASS is imported.", "",
            "Anonymous-policy cases SV26-0460/0461 retain their PARENT_VERIFY_5067 boundary and have no accepted execution verdict in these overlays. Do not infer human policy approval from inventory presence.", ""]
(ROOT / "execution-summary.md").write_text("\n".join(summary))
print(dict(counts))
