it.each(["png", "pdf", "other"] as const)("keeps actual %s media bytes and download identity while translating its owned preview", async kind => {
  const item = { ...artifact, kind, name: `模型文件 {locale}.${kind === "other" ? "bin" : kind}` };
  vi.mocked(listAgentArtifacts).mockResolvedValue([item]);
  const bytes = new Blob([new Uint8Array([0, 1, 123, 255, 10])]);
  vi.mocked(fetchArtifactContent).mockResolvedValue(bytes as unknown as globalThis.Blob);
  const names: string[] = [];
  vi.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(function (this: HTMLAnchorElement) { names.push(this.download); });
  render(app());
  await screen.findByTestId("chat-task-workbench-artifact-export");
  const media = kind === "png" ? screen.getByRole("img") : kind === "pdf" ? document.querySelector("iframe")! : screen.getByText(/此格式可下载查看|Download this format to view it/);
  if (kind === "png") expect(media).toHaveAttribute("alt", `${item.name}, version 2`);
  else if (kind === "pdf") expect(media).toHaveAttribute("title", `${item.name}, version 2`);
  else expect(media).toHaveTextContent("Download this format to view it; all historical versions are retained.");
  expect(screen.getByRole("button", { name: "Download this version" })).toBe(screen.getByTestId("chat-task-workbench-artifact-export"));
  act(() => setLocale("zh-CN"));
  expect(media.isConnected).toBe(true); expect(fetchArtifactContent).toHaveBeenCalledTimes(1);
  expect(URL.createObjectURL).toHaveBeenCalledWith(bytes); expect(URL.revokeObjectURL).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button", { name: "下载此版本" })); expect(names).toEqual([item.name]);
  expect(screen.queryByTestId("artifact-edit-instruction")).toBeNull();
});

it("reports preview byte clipping while retaining the whole download blob", async () => {
  const raw = "x".repeat(256 * 1024) + "原始尾部 {locale}";
  const blob = new Blob([raw]); vi.mocked(fetchArtifactContent).mockResolvedValue(blob as unknown as globalThis.Blob);
  render(app()); await screen.findByTestId("chat-task-workbench-artifact-export");
  await waitFor(() => expect(document.querySelector("pre")?.textContent?.length).toBe(256 * 1024));
  const notice = screen.getByText(/预览仅显示前 256 KB|Preview shows only the first 256 KB/);
  expect(notice).toHaveTextContent("Preview shows only the first 256 KB. Download the full content.");
  expect(URL.createObjectURL).toHaveBeenCalledWith(blob); expect(await blob.text()).toBe(raw);
  act(() => setLocale("zh-CN")); expect(notice.isConnected).toBe(true); expect(fetchArtifactContent).toHaveBeenCalledTimes(1);
});
it("reports bounded real line comparison without truncating the downloadable content", async () => {
  const original = Array.from({ length: 602 }, (_, i) => `raw {locale} ${i}`).join("\n");
  const changed = original.replace("raw {locale} 0", "changed {count} 0");
  const whole = new Blob([changed]);
  vi.mocked(fetchArtifactContent).mockImplementation(async (_id, version) => version === 2 ? whole as unknown as globalThis.Blob : new Blob([original]) as unknown as globalThis.Blob);
  render(app()); fireEvent.click(await screen.findByRole("button", { name: "Compare with version 1" }));
  await screen.findByTestId("artifact-text-diff");
  const notice = screen.getByText(/比较限于前 600 行|Comparison is limited to 600 lines/);
  expect(notice).toHaveTextContent("Comparison is limited to 600 lines and the first 256 KB per version. Download for full content.");
  expect(URL.createObjectURL).toHaveBeenCalledWith(whole); expect(await whole.text()).toBe(changed);
  act(() => setLocale("zh-CN")); expect(notice.isConnected).toBe(true); expect(fetchArtifactContent).toHaveBeenCalledTimes(2);
});

