  await act(async () => pending.resolve(result));
  expect(screen.getByTestId("research-skill-suggestion")).toHaveTextContent("Skill suggestion");
  expect(screen.getByTestId("research-skill-suggestion")).toHaveTextContent(result.assistantMessage);
  expect(screen.getByText("Suggestions generated by provider/raw-model {count}. Research content stays unchanged until you apply them.")).toBeVisible();
