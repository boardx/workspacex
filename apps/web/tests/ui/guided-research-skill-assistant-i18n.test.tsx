function language(locale: Locale) { act(() => setLocale(locale)); }
function deferred<T>() {
  let resolve!: (value: T) => void;
  const promise = new Promise<T>(yes => { resolve = yes; });
  return { promise, resolve };
}
function show(snapshot = initial, sessionKey = "raw-session {count}") {
  const change = vi.fn();
  function Harness() {
    const [current, setCurrent] = React.useState(snapshot);
    return <><GuidedResearchSkillAssistant step={current.step} sessionKey={sessionKey} progressLabel="1/5" snapshot={current}
      onSnapshotChange={next => { change(next); setCurrent(next); }} /><output data-testid="raw-snapshot">{JSON.stringify(current)}</output></>;
  }
  return { ...render(<I18nProvider initialLocale="zh-CN"><Driver /><Harness /></I18nProvider>), change };
}
