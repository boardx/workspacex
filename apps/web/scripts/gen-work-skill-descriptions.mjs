import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../../../skills/", import.meta.url));
const output = new URL("../lib/work-skill-descriptions.generated.ts", import.meta.url);
const descriptions = new Map();

for (const pack of readdirSync(root, { withFileTypes: true })) {
  if (!pack.isDirectory() || !pack.name.startsWith("work-")) continue;
  for (const dir of readdirSync(join(root, pack.name), { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const file = join(root, pack.name, dir.name, "SKILL.md");
    const content = readFileSync(file, "utf8");
    const id = /^    stableId: (S\d{3})\s*$/m.exec(content)?.[1];
    const purpose = /^## (?:这个 Skill )?解决什么问题\s*\n\s*(.+)/m.exec(content)?.[1];
    if (!id || !purpose) throw new Error(`Missing stable ID or purpose in ${file}`);
    const description = purpose.replace(/\*\*|`/g, "").trim();
    const previous = descriptions.get(id);
    if (previous && previous !== description) throw new Error(`Conflicting descriptions for ${id}`);
    descriptions.set(id, description);
  }
}

const data = Object.fromEntries([...descriptions].sort(([a], [b]) => a.localeCompare(b)));
const source = `// Generated by scripts/gen-work-skill-descriptions.mjs from authored SKILL.md purpose sections.
export const WORK_SKILL_DESCRIPTIONS: Readonly<Record<string, string>> = ${JSON.stringify(data, null, 2)};
`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source) throw new Error("Work Skill descriptions are out of date");
} else {
  writeFileSync(output, source);
}
