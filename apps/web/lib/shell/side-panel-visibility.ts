/**
 * 侧栏从多宽开始出现 —— **一处声明**，三个元素共用。
 *
 * ## 这修的是什么（2026-09-23，R2 复盘清单第 4 件）
 *
 * 右栏、它的「收起」按钮、收起后那条「展开」轨，此前各自写着 `xl:block` / `xl:flex`
 * （xl = 1280px）。于是在 1280 以下：**右栏整条不存在，而且没有任何入口把它叫出来**——
 * 不是折叠，是没有。1152 / 1180 / 1280 这些常见笔记本逻辑宽度正好落在下面，
 * 结果就是「我的结果面板呢」。
 *
 * ⚠ `app-shell.tsx` 里 UIUX-CK-1 那段注释写着「右栏在 xl 以下整个消失……加收起/展开
 * toggle」，读起来像是这件事已经修过了。**没有**：那次加的 toggle 本身也是 `xl:flex`，
 * 修掉的只是「xl 以上永远占位」那一半。注释描述的是意图，类名描述的是行为，
 * 两者不一致时以类名为准（[[static-trace-is-not-live-fact]] 的同一形状）。
 *
 * ## 为什么是常量而不是"约定都写 lg"
 *
 * 真正会出事的不是断点高低，是**三个元素不一致**：只要面板降到 lg、而「展开」轨还留在
 * xl，就会出现「面板被收起后在 lg 宽度下再也展不开」——比原来的问题更隐蔽。
 * 写成一处常量，三处引用，分叉在构造上就不可能，不靠谁记得同步改三处。
 *
 * lg（1024px）以下走的是另一套布局（`MobileTabs`），侧栏本来就不参与，所以下界取 lg。
 */

/** 侧栏本体：到达断点才显示为块。 */
export const SIDE_PANEL_VISIBLE = "lg:block";

/** 侧栏上的按钮与收起后的展开轨：到达断点才显示为 flex。 */
export const SIDE_PANEL_VISIBLE_FLEX = "lg:flex";

/**
 * 上面两个常量共用的那个断点前缀。
 *
 * 测试拿它来断言「三处用的是同一个断点」——断言的是**一致性**，不是某个具体数值，
 * 所以哪天产品决定改成 md 或 xl，改常量即可，门不会因为数值变化而误红。
 */
export const SIDE_PANEL_BREAKPOINT = "lg";
