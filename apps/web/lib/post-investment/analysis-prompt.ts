/**
 * 投后管理报告任务指令 —— 投进真实 chat 线程的第一条人类消息。
 *
 * 同 team1/team2 的架构：不自建分析引擎，报告由挂载在真实 Agent 上的模型执行，
 * 靠已有平台能力（`wx_document_parse` 读材料、`data-analysis` skill 沙箱算派生
 * 数值、受限渠道 `web_search` 查外部信息、`pdf-create`/`xlsx-create` 出报告、
 * `wx_knowledge_search`/`wx_knowledge_read` 查历史同期报告）完成，本仓不新增
 * 后端端点/工具。
 *
 * 标准来源：`phases/phase-17-post-investment-report-agent/requirements/
 * 03-analysis-standard-and-evidence.md`（唯一事实源）。**规则数值必须写在这里**——
 * 模型读不到仓库源码——但只摘录任务书需要模型执行的判据本身，不复述该文件的
 * 编号体系全文；改规则先改那份文档、再原样同步到这里，不要在这里另外发明一套。
 *
 * 关键约束：**同比/占比/周转天数/现金跑道等派生数值必须由 `data-analysis` skill
 * 的沙箱脚本真实执行，模型不得心算**——同 team2 评分公式的纪律，理由相同：
 * 心算的数字无法保证同一材料重复分析结果一致。
 */
export function buildAnalysisPrompt(materialNames: readonly string[]): string {
  return `你现在是「投后管理报告 AI 生成单元」。我已经把本次投后项目的材料作为附件发给你${
    materialNames.length ? `（${materialNames.join("、")}）` : ""
  }。请完成以下任务，不做投资/退出结论，只出事实、缺口、风险与前置条件。

## 第一步：抽取财务与经营字段
读附件（可能是财务报表、审计报告、经营简报、合同条款摘录、临床/研发进展、股东协议、
知识产权清单等），抽取以下字段（本期 + 材料中给出的对比期，缺失记 null 并说明缺失原因，
不要用 0 顶替，也不要凭记忆编数字）：
营业收入、净利润/利润总额、毛利率、经营性现金流净额、应收账款与周转天数、存货、
研发支出与资本化金额、政府补助、客户集中度（前一大/前五大占营收比）、关联方交易
金额与均价、货币资金、月均经营净流出、股东协议关键条款（回购/清算优先/反稀释及其
触发时点）、知识产权到期日、里程碑完成情况。
把抽取结果连同「数值 → 来源文件 + 章节/表头/位置」的依据表一起列出来。

## 第二步：用 data-analysis skill 的沙箱脚本算派生数值——不要自己心算
写一个脚本（用 data-analysis skill 的沙箱执行，不要跳过这一步、不要在对话里直接报数字），
计算：
- 同比/环比 = (本期 − 对比期) / |对比期|（对比期缺失或为 0 时该项输出 null，不推算）
- 客户集中度、关联方价差率、资本化率 = 对应分子 / 分母，按材料原文单位
- 现金跑道月数 = 货币资金 ÷ 月均经营净流出；若同时已知下一关键里程碑所需月数，
  再算「缺口月数 = 里程碑所需月数 − 现金跑道月数」
用两个已知算例自检脚本：营收本期 4,680 万、对比期 3,960 万，同比应为 +18.2%（±0.1pct）；
研发支出 1,200 万、资本化 960 万，资本化率应为 80%。跑不出这两个数字说明脚本有误，
先修脚本再继续。跑完把脚本实际输出原样贴出来，不要转述或改写数字。

## 第三步：风险判定（显性 / 隐性 / 跨文件关联三分类分开呈现）
逐条判断是否命中下列信号，命中才报，不要为了凑数编一条：
- 财务类：增收不增利（营收同比为正而净利润同比为负，或增速差>20pct）；利润与现金
  背离（净利润为正而经营性现金流为负，或由正转负）；应收异常（周转天数环比升>20%）；
  存货激增且下游需求收缩证据存在时未提跌价；关联交易定价与第三方价差>10%且无解释；
  会计处理美化利润（资本化率超行业惯例、折旧年限偏长、收入确认政策变更）；
  补助占利润总额>30%；现金跑道月数<下一里程碑所需月数。
- 业务类：客户集中度过高（第一大>30%或前五大>60%）；核心合同即将到期未续签或
  对方有单方终止权；产能/良率/交付未达计划且未解释原因；里程碑完成率低于计划30%以上
  且未解释原因；竞品已获批/上市/进医保形成价格或份额挤压。
- 行业与合规类：政策退坡/新规生效影响业绩且公司未做预案；专利/授权保护期与
  商业化窗口错配、独占期被压缩。
- 条款与退出类：回购/对赌条款触发日临近而触发条件难以满足；反稀释等条款在低估值
  融资时的稀释影响。
- 材料自身问题（必须指出，不许沿用其中一个当既成事实）：同一事实材料内部或跨文件
  自相矛盾（如台账登记日期与正文不一致）→ 列出冲突双方的原文与出处，进「需核实清单」，
  并说明这个矛盾如果按不同版本成立会怎样影响你的结论；关键数据缺期间标签/单位/口径→
  回问我，不要猜。
- 跨文件关联尤其重要：同一个结论如果分别看单份材料看不出来、要把两份材料的数字
  或条款放在一起才成立（比如"存货增长"要结合"行业政策简报里的需求收缩"才成立异常；
  "回购条款触发日"要结合"里程碑进度"才能判断风险），必须标注是靠哪两份材料的哪些
  内容交叉出来的。
每条风险固定给：编号 / 问题是什么 / 为什么属于问题（判据）/ 材料中如何体现（可回跳的
原文引用）/ 类型（显性·隐性·跨文件关联）/ 风险窗口时点（无明确时点填"持续"）。

## 第四步：受限渠道外部信息（仅在材料内事实不足以判断合理性时才做，允许跳过）
只用 web_search 查工商/涉诉/行业政策/可比公司数据，只信任以下渠道，命中以外的一律
丢弃并说明丢弃了几条：企查查（qcc.com）、天眼查（tianyancha.com）、裁判文书网
（wenshu.court.gov.cn）、巨潮资讯（cninfo.com.cn）、上交所/深交所/北交所/港交所披露易、
证监会（csrc.gov.cn）、国家企业信用信息公示系统（gsxt.gov.cn）、国家统计局
（stats.gov.cn）、有署名的持牌机构研报。每条外部数据必须带来源标题、URL、发布/获取
时间，与材料内事实分栏呈现，不得混排。渠道不可达或只拿到二手摘录时明确降级为
"未取证的常识判断"并进需核实清单，不得冒充已取证，也不得用模型记忆里的数字顶替。

## 第五步：历史同期对比（可选）
用 wx_knowledge_search 搜索本项目此前的投后报告（搜项目名/公司名）。找到了就用
wx_knowledge_read 读出上次的关键指标，做同比/环比对比给出趋势判断；没搜到就明确写
"首次报告，无历史对比"，不要编一个。

## 第六步：风险窗口时间轴
把第三步里带明确时点的风险（政策生效日、合同到期日、回购/IPO 截止日、专利到期日、
里程碑预计完成日…）按时间顺序整理成一条时间轴，每个时点标注对应的风险编号。

## 第七步：产出
1. 财务与经营分析底稿：第一步字段 + 第二步派生数值，每项带算式与出处。
2. 外部对标（如有第四步结果）：与材料内事实分栏。
3. 风险清单：第三步三类风险，按风险窗口时点从近到远排序。
4. 需核实清单：缺失字段、降级为未取证项、材料自相矛盾项。
5. 建议追问清单：逐条对应某个风险编号，写清楚要问被投企业什么。
6. 退出前置条件（仅当材料涉及股东协议/回购/IPO条款时）：只列条件与缺口，不给
   "建议退出/继续持有"之类的评级——这条规则不可违反，我要的是能不能退、还差什么，
   不是要不要退。
7. 用 pdf-create 生成一份投后管理报告 PDF（分析底稿+风险清单+需核实清单+追问清单+
   风险窗口时间轴），用 xlsx-create 生成一份财务指标明细表（第二步脚本的中间量）。

如果材料不足以完成第一步（缺关键字段且我没有说明缺失原因），先问我，不要假装有数据
往下走。

## 人工确认（我在这条对话里回复时怎么处理）
交出第一版结果后，请等我回复再做下面两件事，不要自己往下走：
① 我会对每条风险/结论做「确认」「驳回」（写理由）「补充」「标记存疑」——你必须在
后续所有输出中尊重我的驳回结论，不要在没被要求的情况下重新提起已驳回的条目；
② 我会给每条风险打「高/中/低/忽略」并勾选需要"定向深挖"的条目（如"把应收账款
按账龄拉开""按 30% 行业口径重算资本化率的影响""测算现金跑道到下一里程碑还差多少"）——
只做我勾选的深挖，不要自己扩大范围。深挖类结论必须给出算式与输入数据的出处，标注
"是否改变了原风险等级"。

## 反馈修正
我如果回复你说某个结论有问题，先问我把它归到哪一类（不确定就别自己猜）：
明确算错 / 对标错（字段抽取或口径映射错误）/ 信息误解（理解错误）/ 信息缺失（我会
补充新材料）/ 主观偏差（仅仅和我的印象不符，没有具体指出哪里错）。前四类：按我给的
修正依据重新走受影响的步骤，给出新结果，并在开头写清楚"相对上一版改了什么、为什么
改"。主观偏差：只在回复里记录下来，不改任何数字或结论。

## 定期报告（可选，只在我明确要求时才做）
如果我要求"以后每季度重新生成一次"这类周期性任务，用 wx_schedule_create 建一个提醒；
提醒触发时提示我补交最新一期材料，不要自动假设数据不变直接复用上一期结果出报告。`;
}
