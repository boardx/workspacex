/**
 * 评级任务指令 —— 投进真实 chat 线程的第一条人类消息。
 *
 * 同 team1（`lib/ic-review/review-prompt.ts`）的架构：不自建分析引擎，评级由挂载在
 * 真实 Agent 上的模型执行，靠已有平台 skill 完成，本仓不新增后端端点/工具。
 *
 * 关键约束：**评分公式必须由 `data-analysis` skill 的沙箱脚本真实执行，模型不得
 * 心算给出分数**——这条规则本身就是任务书要传达的内容，因此规则数值必须以文字形式
 * 出现在这里（模型读不到仓库源码）。
 *
 * ⚠ 但数值**不在本文件声明**：第三步那一段由 `renderRuleBook()` 从
 * `packages/contracts/src/postinvest-rating-rules.ts` 渲染，与
 * `apps/api/src/domain/postinvest-rating/scoring.ts` 读同一份常量。此前这里手抄了一份，
 * 两处都自洽、改一处不会有任何东西变红——改规则只改规则手册那一个文件。
 *
 * 第三个参数是本次评级所属的真实项目名（R3-1）——记忆协议按项目名检索与写入，项目名
 * 不一致就等于没有历史。不传时任务书不写死一个名字，让模型问我。
 *
 * 第二个参数是 R3-3 的「数据缺失说明」表单结果——人工确认事实，模型不得自行推断
 * （见 `missing-reason.ts` 头注）。不传（如发布 Agent 时把本任务书固化成 instructions）
 * 就不渲染那一段。
 */
import type { postinvestRating } from "@repo/contracts";
import { TRUSTED_SOURCE_SEED_DOMAINS } from "@repo/contracts/postinvest-rating";
import { renderRuleBook } from "@repo/contracts/postinvest-rating-rules";
import { buildMissingReasonBrief } from "./missing-reason";
import { RATING_MEMO_TAG, buildMemoryProtocol } from "./rating-memo";

type MissingDataReason = postinvestRating.MissingDataReason;

export function buildRatingPrompt(
  materialNames: readonly string[],
  missingReason?: MissingDataReason,
  projectName?: string,
): string {
  const brief = missingReason ? buildMissingReasonBrief(missingReason) : null;
  return `你现在是「投后财务项目评级 Agent」。${
    projectName ? `本次评级的项目是「${projectName}」，记忆协议里的项目名就用它。` : ""
  }我已经把本次投后项目的材料作为附件发给你${
    materialNames.length ? `（${materialNames.join("、")}）` : ""
  }。请完成以下任务。
${brief ? `\n${brief}\n` : ""}
## 第一步：抽取字段
读附件（可能是财务报表 Excel、审计报告 PDF、访谈录音转写、经营报告 PPT），抽取以下字段
（本年 / 上年，缺失记 null，不要用 0 顶替，并说明缺失原因）：
营业收入、净利润、货币资金、近 12 月经营现金流出、经营活动现金流净额、应收账款、存货、
其他应收款、总资产、净资产、流动资产、流动负债、报表口径（合并/单体）、报告期。
把抽取结果连同「数值 → 来源文件 + 章节/表头/位置」的依据表一起列出来。

## 第二步：数据质量判定
${
    brief
      ? "先看上面那段我确认过的事实：缺失原因、是否只有单体报表 / 经营报告、是否无上年对比，\n一律以那一段为准；那一段没写的，就是我还没确认，需要时问我，不要从材料语气里推断。\n在此前提下按下表判定标注"
      : "缺失原因这类只有我知道的事实，我没说就是没确认——需要时问我，不要从材料语气里推断。\n按下表判定标注"
  }（可多选），并说明触发依据：
- 有审计报告或财务报表 → 正常评分
- 仅未合并子公司单体报表 / 仅经营报告 → 标注「数据不完整」
- 无上年对比数据 → 增长类指标按体量给基础分（见下方公式）
- 无财务报表（保密期/并购等正常原因）→ 明确说明"需要往期报表作为暂估依据"，向我要往期数据，不要自己编
- 无财务报表（诉讼/失联/停业/破产等异常原因）→ 直接判 E，标注「公司经营异常」，跳过第三步
- 触发第三步规则手册末尾那两条「数据疑似异常」比率之一 → 标注「数据疑似异常」（阈值见手册，不要另记一套）

## 第三步：用 data-analysis skill 的沙箱脚本计算——不要自己心算
写一个 Python 脚本（用 data-analysis skill 的沙箱执行，不要跳过这一步、不要在对话里直接报数字），
严格实现以下公式：

${renderRuleBook()}

跑完脚本后，把实际输出（S1/S2/S3、总分、等级、每一步的中间量）原样贴出来，不要转述或改写数字。
用固定的例子核对一遍你的脚本：营收本年 1.5 亿、上年 1 亿（+50%），增长率得分应该正好是 90；
上年/本年比值恰好 1.3（下滑），增长率得分应该正好是 -35。跑不出这两个数字说明脚本有误，先修脚本再继续。

## 第四步：历史同期对比
用记忆协议里搜到的上一条 ${RATING_MEMO_TAG} 记录（不要用 wx_knowledge_search 找你自己以前
发布的报告，那条路搜不到——agent 产出的文件不进组织索引）。拿上次的 S1/S2/S3、总分与等级
做同比/环比对比，给出「趋势判断」（改善/平稳/恶化）；归因候选只能引用本次或上次报表数据里的
原话，标注来源，不得把「伴随」写成「导致」，除非访谈转录稿里当事人原话如此并注明是陈述而非
事实。记忆里没有本项目记录就明确写「首次评级，无趋势判断」，不要编一个。
如果我上传了往期报表原件，那属于我提供的材料，正常用 wx_document_parse 读——这一条限制
只针对「搜你自己以前的产出」。

## 第五步：受限渠道行业背景（可选，允许跳过）
只用 web_search 搜公司名/行业名（不要搜财务数值）。只信任以下域名（含子域），命中以外的
一律丢弃并说明丢弃了几条：${TRUSTED_SOURCE_SEED_DOMAINS.join("、")}，以及被评公司官网。
这一步不改变任何分数，只作为文字补充。

## 第六步：产出
1. 结论卡：等级 + 颜色 + 含义 + 投后管理建议（原样抄第三步分级表对应行，不要改写）。
2. 依据表：每个数值的来源。
3. 不确定性标注：缺失字段、估算项、数据质量标注、第四步趋势判断。
4. 用 pdf-create 生成一份评级报告 PDF（结论卡+依据表+不确定性+趋势对比），用
   xlsx-create 生成一份指标与得分明细表（第三步脚本的中间量）。
5. 按下面的记忆协议写一条评级记录——这一步不做，下一次评级就没有历史可比。

如果材料不足以完成第一步（缺关键字段且我没有说明缺失原因），先问我，不要假装有数据往下走。

## 反馈修正（我在这条对话里回复指出问题时怎么处理）
我如果回复你说某个结论有问题，先问我把它归到哪一类（不确定就别自己猜）：
明确算错 / 对标错（字段抽取或口径映射错误）/ 信息误解（转录或文档理解错误）/
信息缺失（我会补充新材料）/ 主观偏差（仅仅和我的印象不符，没有具体指出哪里错）。
前四类：按我给的修正依据重新走第一到第六步里受影响的部分，给出新的结论卡，并在开头
写清楚「相对上一版改了什么、为什么改」。主观偏差：只在回复里记录下来，不改任何
分数或结论，不要因为「听起来不太对」就调整权重或口径——这条规则不可违反。
前四类改完后，按记忆协议写一条修正记录；主观偏差那一类不写。

${buildMemoryProtocol()}

## 定期评级（可选，只在我明确要求时才做）
如果我要求"以后每季度重新评一次"这类周期性检查，用 wx_schedule_create 建一个提醒；
提醒触发时提示我补交最新一期报表，不要自动假设数据不变直接复用上一期结果出分。`;
}
