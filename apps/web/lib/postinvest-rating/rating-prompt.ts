/**
 * 评级任务指令 —— 投进真实 chat 线程的第一条人类消息。
 *
 * 同 team1（`lib/ic-review/review-prompt.ts`）的架构：不自建分析引擎，评级由挂载在
 * 真实 Agent 上的模型执行，靠已有平台 skill 完成，本仓不新增后端端点/工具。
 *
 * 关键约束：**评分公式必须由 `data-analysis` skill 的沙箱脚本真实执行，模型不得
 * 心算给出分数**——这条规则本身就是任务书要传达的内容，因此规则数值必须写在这里
 * （模型读不到仓库源码）。数值与 `apps/api/src/domain/postinvest-rating/scoring.ts`
 * （issue #3676 已交付、已用 10 个场景验收）逐字一致，那是本文件数值的参照实现，
 * 改规则先改那份、再原样同步到这里——不要在这里另外发明一套。
 */
export function buildRatingPrompt(materialNames: readonly string[]): string {
  return `你现在是「投后财务项目评级 Agent」。我已经把本次投后项目的材料作为附件发给你${
    materialNames.length ? `（${materialNames.join("、")}）` : ""
  }。请完成以下任务。

## 第一步：抽取字段
读附件（可能是财务报表 Excel、审计报告 PDF、访谈录音转写、经营报告 PPT），抽取以下字段
（本年 / 上年，缺失记 null，不要用 0 顶替，并说明缺失原因）：
营业收入、净利润、货币资金、近 12 月经营现金流出、经营活动现金流净额、应收账款、存货、
其他应收款、总资产、净资产、流动资产、流动负债、报表口径（合并/单体）、报告期。
把抽取结果连同「数值 → 来源文件 + 章节/表头/位置」的依据表一起列出来。

## 第二步：数据质量判定
按下表判定标注（可多选），并说明触发依据：
- 有审计报告或财务报表 → 正常评分
- 仅未合并子公司单体报表 / 仅经营报告 → 标注「数据不完整」
- 无上年对比数据 → 增长类指标按体量给基础分（见下方公式）
- 无财务报表（保密期/并购等正常原因）→ 明确说明"需要往期报表作为暂估依据"，向我要往期数据，不要自己编
- 无财务报表（诉讼/失联/停业/破产等异常原因）→ 直接判 E，标注「公司经营异常」，跳过第三步
- (应收+存货)/收入 > 80% → 标注「数据疑似异常」
- 其他应收款/总资产 > 20%，或其他应收款同比增长 > 50% 且经营现金流为负 → 标注「数据疑似异常」

## 第三步：用 data-analysis skill 的沙箱脚本计算——不要自己心算
写一个 Python 脚本（用 data-analysis skill 的沙箱执行，不要跳过这一步、不要在对话里直接报数字），
严格实现以下公式：

**S1（权重 40%）= 增长率得分 × 40% + 营收体量得分 × 60%**
营收体量得分：≥5亿→100，3-5亿→90，1-3亿→72，5000万-1亿→52，1000万-5000万→30，<1000万→0
增长率得分：增长 = 90 × log1.5(本年营收/上年营收)；下滑 = -35 × log1.3(上年营收/本年营收)；
无上年数据 = 按营收体量得分（同上表）

**S2（权重 30%）= 净利润增长率得分 × 40% + 绝对盈利水平得分 × 60%**
绝对盈利水平得分：≥1亿→100，5000万-1亿→90，2000万-5000万→82，1000万-2000万→75，
500万-1000万→65，100万-500万→55，0-100万→45，亏损1000万以内→-5~-15（线性，越亏越低），
亏损1000万-1亿→-15~-30（线性），亏损≥1亿→-70
净利润增长率得分：扭亏为盈=70~90（上年亏损越大越高，按 min(上年亏损,1亿)/1亿 线性映射到 70~90）；
连续亏损收窄=收窄比例×100（0~100）；连续亏损扩大=负分（按扩大比例×100，封顶-100）；
连续盈利增长=80×log2(本年/上年)；连续盈利下滑=温和惩罚，最多-25（按下滑比例×25 取负）；
由盈转亏=-70；无上年数据：盈利+40，亏损-20

**S3（权重 30%）= 现金自给月数得分**
现金自给月数 = 货币资金 ÷ (近12月经营现金流出÷12)
得分：≥24月→100；12-24月→50~100线性；6-12月→0~50线性；3-6月→-30~0线性；
1-3月→-60~-30线性；0.3-1月→-80~-60线性；<0.3月→-85

**总分 = 100 + S1×40% + S2×30% + S3×30%**
分级：>140→A（绿，优秀，正常跟踪考虑追加投资）；100-140→B（蓝，正常，保持跟踪优化薄弱环节）；
70-100→C（橙，关注，关注经营变化制定改善计划）；40-70→D（红，风险，重点监控启动介入评估）；
<40→E（深红，高风险，启动法律程序清算/重组）

**降级触发（覆盖上面算出的等级）**：净资产<0 → 至多 D；净资产<0 且经营现金流为负且流动比率<1 → 至多 E。

跑完脚本后，把实际输出（S1/S2/S3、总分、等级、每一步的中间量）原样贴出来，不要转述或改写数字。
用固定的例子核对一遍你的脚本：营收本年 1.5 亿、上年 1 亿（+50%），增长率得分应该正好是 90；
上年/本年比值恰好 1.3（下滑），增长率得分应该正好是 -35。跑不出这两个数字说明脚本有误，先修脚本再继续。

## 第四步：受限渠道行业背景（可选，允许跳过）
只用 web_search 搜公司名/行业名（不要搜财务数值），只信任交易所/证监会/企业信用公示系统这类
官方渠道，其它来源丢弃并说明丢弃了几条。这一步不改变任何分数，只作为文字补充。

## 第五步：产出
1. 结论卡：等级 + 颜色 + 含义 + 投后管理建议（原样抄第三步分级表对应行，不要改写）。
2. 依据表：每个数值的来源。
3. 不确定性标注：缺失字段、估算项、数据质量标注。
4. 用 pdf-create 生成一份评级报告 PDF（结论卡+依据表+不确定性），用 xlsx-create 生成一份
   指标与得分明细表（第三步脚本的中间量）。

如果材料不足以完成第一步（缺关键字段且我没有说明缺失原因），先问我，不要假装有数据往下走。`;
}
