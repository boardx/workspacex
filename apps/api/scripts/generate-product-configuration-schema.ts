import {readFileSync,writeFileSync,existsSync} from "node:fs";
import {resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {PERSONAL_PRICE_CATALOG} from "../src/domain/billing/personal-price-catalog";
const target=new URL("../migrations/20261102050000_product_configuration.sql",import.meta.url);
const quote=(value:string)=>"'"+value.replaceAll("'","''")+"'";
/** Existing v1 values seed new columns once. Runtime pricing reads credit_packages. */
export function renderProductConfigurationSchema(){
 const topups=Object.values(PERSONAL_PRICE_CATALOG).flat().filter(p=>p.kind==="credit_topup").map(p=>quote(p.sku)).join(",");
 const historicMonthly=PERSONAL_PRICE_CATALOG.cn.find(p=>p.kind==="subscription")!.monthlyCredits;
 const subscriptions=Object.entries(PERSONAL_PRICE_CATALOG).flatMap(([market,products])=>products.filter(p=>p.kind==="subscription").map((p,index)=>`(${quote(p.sku)},${quote(market)},${quote(p.currency)},${p.amountMinor},${p.monthlyCredits},${quote(p.cycle)},${index})`)).join(",\n");
 return `-- Generated by generate-product-configuration-schema.ts. Existing approved v1 defaults seed only.
-- Same table, one current product fact. Legacy fixtures do not become new storefront products.
ALTER TABLE credit_packages ADD COLUMN IF NOT EXISTS product_kind text NOT NULL DEFAULT 'legacy' CHECK(product_kind IN ('legacy','credit_topup','subscription'));
ALTER TABLE credit_packages ADD COLUMN IF NOT EXISTS billing_cycle text CHECK(billing_cycle IN ('month','year'));
ALTER TABLE credit_packages ADD COLUMN IF NOT EXISTS included_seats integer;
ALTER TABLE credit_packages ADD COLUMN IF NOT EXISTS extra_seat_amount_fen integer;
ALTER TABLE credit_packages ADD COLUMN IF NOT EXISTS extra_seat_monthly_credits integer;
DO $constraints$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='credit_packages'::regclass AND conname='credit_package_cycle') THEN
  ALTER TABLE credit_packages ADD CONSTRAINT credit_package_cycle CHECK((product_kind='subscription')=(billing_cycle IS NOT NULL));
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='credit_packages'::regclass AND conname='credit_package_team_parameters') THEN
ALTER TABLE credit_packages ADD CONSTRAINT credit_package_team_parameters CHECK(
 (included_seats IS NULL AND extra_seat_amount_fen IS NULL AND extra_seat_monthly_credits IS NULL) OR
 (owner_type='team' AND product_kind='subscription' AND included_seats IS NOT NULL AND extra_seat_amount_fen IS NOT NULL AND extra_seat_monthly_credits IS NOT NULL AND included_seats>0 AND extra_seat_amount_fen>0 AND extra_seat_monthly_credits>0));
 END IF;
END;
$constraints$;
UPDATE credit_packages SET product_kind='credit_topup' WHERE product_kind='legacy' AND package_id IN (${topups});
DO $configuration$
DECLARE entry record;
BEGIN
 FOR entry IN SELECT * FROM (VALUES ${subscriptions}) AS defaults(sku,market,currency,amount,credits,cycle,sort_order)
 LOOP
  INSERT INTO credit_packages(package_id,region,currency,amount_fen,base_credits,bonus_credits,total_credits,owner_type,enabled,sort_order,product_kind,billing_cycle)
   VALUES(entry.sku,entry.market,entry.currency,entry.amount,entry.credits,0,entry.credits,'user',true,entry.sort_order,'subscription',entry.cycle)
   ON CONFLICT(package_id) DO NOTHING;
  UPDATE credit_packages SET product_kind='subscription',billing_cycle=entry.cycle WHERE package_id=entry.sku AND product_kind='legacy';
 END LOOP;
END;
$configuration$;
ALTER TABLE billing_personal_terms ADD COLUMN IF NOT EXISTS monthly_credits integer NOT NULL DEFAULT ${historicMonthly} CHECK(monthly_credits>0);
COMMENT ON COLUMN billing_personal_terms.monthly_credits IS 'Immutable paid entitlement snapshot; the default preserves historical v1 terms. New issuers supply their frozen purchase quantity.';
COMMENT ON COLUMN credit_packages.product_kind IS 'Current storefront products read server-side; content fingerprint is the public catalog version. Paid purchases retain independent immutable product snapshots.';
`;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const content=renderProductConfigurationSchema();
 if(process.argv.includes("--check")){if(!existsSync(target)||readFileSync(target,"utf8")!==content)throw Error("product_configuration_seed_drift");console.log("Product configuration seed matches approved historical defaults.");}
 else writeFileSync(target,content);
}
