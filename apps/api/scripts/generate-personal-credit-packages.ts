import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PERSONAL_PRICE_CATALOG, PERSONAL_PRICE_CATALOG_VERSION } from "../src/domain/billing/personal-price-catalog";

const migration = new URL("../migrations/20261101220000_personal_credit_packages.sql", import.meta.url);
const quote = (value: string) => `'${value.replaceAll("'", "''")}'`;

/** Generated artifact, never a second hand-maintained price declaration. */
export function renderPersonalCreditPackages(): string {
  const rows: string[] = [];
  for (const [market, products] of Object.entries(PERSONAL_PRICE_CATALOG)) {
    let order = 0;
    for (const product of products) {
      if (product.kind !== "credit_topup") continue;
      rows.push(`      (${quote(product.sku)}, ${quote(market)}, ${quote(product.currency)}, ${product.amountMinor}, ${product.credits}, ${++order})`);
    }
  }
  return `-- Generated by scripts/generate-personal-credit-packages.ts; do not hand edit.
-- Source: ${PERSONAL_PRICE_CATALOG_VERSION}. Add a new version/migration for future prices.
UPDATE credit_packages SET enabled=false WHERE package_id LIKE 'pkg-%';

DO $pricing$
DECLARE
  seed RECORD;
  stored credit_packages%ROWTYPE;
BEGIN
  FOR seed IN SELECT * FROM (VALUES
${rows.join(",\n")}
    ) AS catalog(package_id,region,currency,amount_fen,credits,sort_order)
  LOOP
    INSERT INTO credit_packages(package_id,region,currency,amount_fen,base_credits,bonus_credits,bonus_rate,total_credits,owner_type,enabled,sort_order)
      VALUES(seed.package_id,seed.region,seed.currency,seed.amount_fen,seed.credits,0,0,seed.credits,'both',true,seed.sort_order)
      ON CONFLICT(package_id) DO NOTHING;
    SELECT * INTO stored FROM credit_packages WHERE package_id=seed.package_id;
    IF stored.region IS DISTINCT FROM seed.region OR stored.currency IS DISTINCT FROM seed.currency
      OR stored.amount_fen IS DISTINCT FROM seed.amount_fen OR stored.base_credits IS DISTINCT FROM seed.credits
      OR stored.bonus_credits<>0 OR stored.bonus_rate<>0 OR stored.total_credits IS DISTINCT FROM seed.credits
      OR stored.owner_type<>'both' THEN
      RAISE EXCEPTION 'pricing_catalog_snapshot_conflict: %', seed.package_id;
    END IF;
  END LOOP;
END;
$pricing$;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = renderPersonalCreditPackages();
  if (process.argv.includes("--check")) {
    if (!existsSync(migration) || readFileSync(migration, "utf8") !== expected) {
      console.error("Personal credit package SQL differs from the server catalog; regenerate it.");
      process.exitCode = 1;
    } else console.log("Personal credit package SQL matches the server catalog.");
  } else {
    writeFileSync(migration, expected);
    console.log(fileURLToPath(migration));
  }
}
