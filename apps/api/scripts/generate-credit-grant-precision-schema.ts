import {existsSync,readFileSync,writeFileSync} from "node:fs";
import {resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {CreditBalance} from "@repo/contracts/billing-credits";
import {renderWelcomeCreditTrigger} from "./generate-welcome-credit-schema";
const migration=new URL("../migrations/20261102030500_credit_grant_precision.sql",import.meta.url);
export function renderCreditGrantPrecisionSchema():string {
 const max=CreditBalance.maxValue,step=CreditBalance._def.checks.find(check=>check.kind==="multipleOf");
 if(max===null||!Number.isSafeInteger(max)||!step||step.kind!=="multipleOf")throw Error("credit_precision_schema_invalid");
 const scale=String(step.value).split(".")[1]?.length??0;
 if(scale<1||step.value*10**scale!==1)throw Error("credit_precision_schema_invalid");
 const precision=String(max).length+scale;
 return `-- Generated by scripts/generate-credit-grant-precision-schema.ts; do not hand edit.
-- Preserve historical rows and the original range; only cumulative grant scale widens.
ALTER TABLE credit_wallets ALTER COLUMN total_granted TYPE numeric(${precision},${scale}) USING total_granted::numeric(${precision},${scale});
ALTER TABLE credit_wallets DROP CONSTRAINT IF EXISTS credit_wallets_total_granted_bound;
ALTER TABLE credit_wallets ADD CONSTRAINT credit_wallets_total_granted_bound CHECK(total_granted<=${max});

${renderWelcomeCreditTrigger(true)}`;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const expected=renderCreditGrantPrecisionSchema();
 if(process.argv.includes("--check")){
  if(!existsSync(migration)||readFileSync(migration,"utf8")!==expected){console.error("Credit grant precision schema differs from contract sources.");process.exitCode=1;}
  else console.log("Credit grant precision schema matches contract sources.");
 }else{writeFileSync(migration,expected);console.log(fileURLToPath(migration));}
}
