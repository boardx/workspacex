-- 画布模板的**提示词**——人类 2026-08-26 第三轮实测反馈：「现有的历史数据，我看还没有
-- 提示词，这个也是问题，需要修复所有的历史数据」。
--
-- ## 与 title/footer 同一套模式：装帧，不是内容，任何状态都能改
--
-- `prompt_text` 是「顾问写这一段，AI 从提示词里提取字段」（编辑器①「提示词与字段」）的
-- 那段自由文本。它**不进** `sections`，也**不会**被发到运行时模型（`buildCanvasTemplateGuidance`
-- 注入 chat 的是分区名/字段名，不读这一列）——它是**编写模板时**给顾问看的说明，
-- 帮他理解"这个模板要 AI 干什么"，属于编辑辅助材料，不是模板本身的运行时行为。
--
-- 因此走 `updateTemplateMetadata` 写，对**任何状态**生效——已发布模板也能直接改这段
-- 说明文字，不必开新版；物理上碰不到 `sections`，I-4 不受影响。
--
-- ## 默认空串，历史数据由回填脚本补
--
-- 空串 = 编辑器①栏留空，与"没写过"同义。19 个内置模板没有一份可信的历史提示词
-- 原文可抄——不编造，而是**从真实分区结构机械生成**一份功能性默认文案（模板名 +
-- 分区名/字段名列出来），与本仓给分区推演坐标/给区块推演字段类型是同一条纪律：
-- 能从已有事实推的就推，不能推的就留白让人类填，绝不假装有一份"原始提示词"存在过。
--
-- 可独立重放：ADD COLUMN IF NOT EXISTS。

ALTER TABLE canvas_templates ADD COLUMN IF NOT EXISTS prompt_text text NOT NULL DEFAULT '';

COMMENT ON COLUMN canvas_templates.prompt_text IS
  '编辑器①「角色与任务」自由文本，供顾问理解此模板要 AI 产出什么、辅助提取字段。'
  '不进 sections、不发给运行时模型。空串 = 未写。';
