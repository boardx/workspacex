/**
 * Ad-hoc（issue #4181，2026-09-25）—— 判断一条已经记下的结论是不是「决定类」陈述，供
 * `fuseRecall`（`recall.ts`）在召回时把这类结论直接摆进上下文，不受字面 / 图路打分影响。
 *
 * **风格照抄 `memory-intent.ts`**：固定关键词 + 保守的排除规则，不调模型、不猜语义。
 * **在读时（召回）算，不在写时（抽取）算**：这是对 `claims.statement`（已经存在的文本列）的纯函数
 * 分类，跟抽取管线要不要打一个 `decisionLike` 列没有关系——不新增列、不需要迁移（issue 原话）。
 * 如果将来要把这个判断结果物化（比如给界面一个「决定」徽标、或者要跨大量结论批量预计算），
 * 才有理由回头考虑加列；纯粹为了召回这一步，读时算完全够用。
 *
 * ## 为什么比 `memory-intent.ts` 更保守（宁可漏不可误，且误判的代价更高）
 *
 * `memory-intent.ts` 判错，最多是那一轮少开 / 多开一张确认卡——用户看一眼就知道，不会重复发生。
 * 这里判错（尤其是「不该判决定类却判了」），后果是**一条结论从此每一轮都挤占本来只有
 * `DECISION_RECALL_LIMIT` 个名额的强制召回位**，直到人工发现、手动改掉——比误判一次贵得多。
 * 所以：关键词表尽量窄、排除规则尽量宽，任何看得出歧义的情况一律不判定。
 *
 * ## 触发（决定类关键词，均为决定性动词，不含单纯「确定」以外的形容词用法之外的歧义词）
 *
 *   决定 / 选定 / 聚焦 / 确定 / 改为 / 改成 / 定为 / 敲定 / 拍板
 *
 * 这份列表刻意贴合 issue 原文给出的六个词，外加两个同项目里已经在用「谁定的 / 拍板」语义
 * （`recall.ts` 的 `WHO_DECIDED`）的近义词，方便同一批「决定类」表达在查询意图加成与强制召回之间
 * 保持一致口径。**不包含**「打算」「计划」「想」「倾向」——这些是意向、不是已经拍板的决定
 * （「我打算关注 211 高校」比「我决定关注 211 高校」弱得多，误判成决定类的代价对不上）。
 *
 * ## 不触发（逐条钉住，风格同 `memory-intent.ts` 的排除清单）
 *
 * - **问句**：以问号结尾（「这个方向确定了吗？」）；句末疑问语气「…吗/呢/么/是不是/对吗/好吗/行吗/是否/对不对」
 *   （「聚焦 211 高校可以吗」不是决定，是在征求意见）；句中带疑问词「谁/什么/哪/怎么/多少/几/为什么/是否/是不是」
 *   （「决定权归谁」是在问决定权的归属，不是在陈述一个决定）。
 * - **假设 / 条件句**：以「如果/假如/假设/要是/倘若/假使/万一」开头（「如果决定关注 211 高校，预算要重新算」
 *   说的是一个还没发生的条件，不是已经做出的决定；「假设我们选定了 A 方案」同理）。
 * - **引述他人转述、非本人确认的说法**：形如『X 说「…决定…」』『X 说决定…』（「他说决定换方案，但还没最终定」——
 *   这是在转述别人说的话，不是这条结论本身在断言一个已生效的决定；转述的内容可能是错的、过时的、
 *   或对方后来又改了主意，逐字挪进强制召回位风险最大）。
 * - **否定**：「没决定」「没有决定」「不决定」「未决定」「没确定」「未确定」「没选定」「未选定」「没定为」「决定不了」
 *   「确定不了」「定不下来」「选不定」（「v2 上线时间还没决定」明确是「没有」决定，不能反着算成决定类）。
 * - **过短 / 空洞**：整条陈述短到没有实质内容（少于 4 个字符，去掉首尾空白后）——太短的陈述本身
 *   信息量不够，即使命中关键词也没有值得强制召回的实质内容。
 *
 * 与 `memory-intent.ts` 的关系：`memory-intent.ts` 判的是**这一轮用户消息**里「记住 / 忘掉」的指令性
 * 意图；这里判的是**已经写进 claims 表的结论文本**是不是在陈述一个决定——两者读的是不同阶段的
 * 不同文本，互不依赖，也不共用触发词表（「决定」在两边的语境完全不同：一个是用户在要求 agent
 * 做什么，一个是结论本身在断言什么）。
 */

/** 召回时决定类结论的强制上限（issue 建议 3–5，这里取更保守的 3，见 `recall.ts` 的集成注释）。 */
export const DECISION_RECALL_LIMIT = 3;

/** 一条结论要有实质内容才值得强制召回；太短（去掉首尾空白后）的陈述信息量不够。 */
const MIN_STATEMENT_LENGTH = 4;

/** 决定性动词：issue 原文六个 + 项目里已经在用的「拍板/敲定」近义词（见 `recall.ts` 的 `WHO_DECIDED`）。 */
const DECISION_VERBS = "决定|选定|聚焦|确定|改为|改成|定为|敲定|拍板";

/** 命中决定性动词，作触发的第一道门槛。 */
const DECISION_VERB = new RegExp(DECISION_VERBS);

/** 句末问号（含中文问号）。 */
const QUESTION_END = /[?？]\s*$/;
/** 句末疑问语气：「…吗」「…呢」「…是不是」——是在问，不是在陈述一个已经做出的决定。 */
const QUESTION_TAIL = /(?:吗|呢|么|对吗|是吗|好吗|行吗|是不是|对不对|是否)\s*[。.!！~～]*$/;
/** 句中带疑问词：「决定权归谁」「聚焦哪个方向确定了」——问的是决定的归属 / 内容，不是在陈述决定本身。 */
const INTERROGATIVE = /什么|谁|哪|怎么|怎样|咋|多少|几(?!乎)|为何|为什么|是否|是不是|对不对|有没有|能不能|要不要|会不会/;

/** 假设 / 条件句前缀：说的是一个还没发生的条件，不是已经拍板的决定。 */
const HYPOTHETICAL_LEAD = /^(?:如果|假如|假设|要是|倘若|假使|万一)/;

/**
 * 转述他人说法：『X 说「…」』『X 说决定…』『X 表示 / 声称 已经选定…』——这条结论本身在转述别人的话，
 * 不是在断言一个已经生效的决定；转述可能不准、可能过时、对方也可能后来改了主意。
 * 覆盖两种写法：带引号的转述（说 / 表示 / 声称 紧跟引号）；不带引号的转述，决定动词在报告动词后面
 * 不太远处出现（容许「已经 / 说是」这类连接词插在中间，如「他表示已经选定了 A 方案」；8 个字符是
 * 「表示」到决定动词之间常见连接语的宽松上限，不是精确语法分析——按宁可漏不可误的原则，宁可因为
 * 窗口内偶然出现别的字而多排除几条，也不要因为窗口太窄而放过一条转述）。
 */
const REPORTED_SPEECH = new RegExp(
  `(?:说|说是|说过|表示|声称|引用)(?:\\s*[""「『]|[^。！\\n]{0,8}(?=(?:${DECISION_VERBS})))`,
);

/**
 * 否定：「没/没有/不/未/尚未/还没/没能」紧挨着决定动词——「还没决定」「没有确定」「决定不了」
 * 「确定不了」「定不下来」「选不定」。前否定与后缀「不了/不下/不定」两种写法都要接住。
 */
const NEGATED_LEAD = new RegExp(`(?:没有?|不|未|尚未|还没|没能|无法)\\s*(?:${DECISION_VERBS})`);
const NEGATED_TAIL = /(?:决定|确定|选定|定)(?:不了|不下(?:来)?|不定)/;

/**
 * 一条结论是不是在陈述一个「决定类」的事实：命中决定性动词，且不落在任何一条排除规则里。
 * 不确定 / 有歧义一律 false（宁可漏不可误，见文件头）。
 */
export function decisionLike(statement: string): boolean {
  const text = statement.normalize("NFKC").trim();
  if (text.length < MIN_STATEMENT_LENGTH) return false;
  if (!DECISION_VERB.test(text)) return false;
  if (QUESTION_END.test(text) || QUESTION_TAIL.test(text)) return false;
  if (INTERROGATIVE.test(text)) return false;
  if (HYPOTHETICAL_LEAD.test(text)) return false;
  if (REPORTED_SPEECH.test(text)) return false;
  if (NEGATED_LEAD.test(text) || NEGATED_TAIL.test(text)) return false;
  return true;
}
